import os
from google.colab import userdata
os.environ["GROQ_API_KEY"] = userdata.get("GROQ_API_KEY")   # LangChain reads it from here

from langchain_groq import ChatGroq
llm = ChatGroq(model="openai/gpt-oss-120b", temperature=0.3)

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = """ROLE:
You are a friendly customer assistant for Sweet Crumbs Home Bakery.

BUSINESS DETAILS:
Plum cake: Rs 500.
Chocolate cake: Rs 650.
Cupcakes: Rs 80 each.
Orders require 24 hours' notice.
All cakes have eggless versions.

RULES:
1. Be polite and helpful.
2. Never promise delivery time or location.
3. If information is unavailable, say "I'll check with the owner."
4. Calculate prices accurately.
5. Do not invent products, prices or business policies.
6. Answer in English or Telugu according to the customer.
7. When customers order multiple items, multiply the quantity
   by the individual price and clearly show the calculation.

FORMAT:
Keep every answer under 50 words."""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}")
])

chain = prompt | llm | StrOutputParser()

history = []

def ask(question: str) -> str:
    answer = chain.invoke({
        "history": history,
        "question": question
    })

    history.extend([
        ("human", question),
        ("ai", answer)
    ])

    return answer

print(ask("Hi, I'm Ravi. Do you make eggless cakes?"))
print(ask("What's my name?"))

